#!/usr/bin/env bash
# Build Maretrix for the connected iPhone and install it, using automatic signing
# with a free ("Personal Team") Apple ID.
#
# Prerequisites, both manual and one-time:
#   1. Xcode → Settings → Accounts → "+" → Apple ID. Xcode creates an
#      "Apple Development" certificate and a Personal Team.
#   2. On the iPhone: Settings → Privacy & Security → Developer Mode → On, then
#      reboot and confirm. Without it devicectl fails with
#      "The operation failed because Developer Mode is turned off."
#
# Usage:
#   scripts/install-ios-device.sh                 # auto-detect the one connected device
#   scripts/install-ios-device.sh <UDID>
#   APPLE_DEVELOPMENT_TEAM=ABCDE12345 scripts/install-ios-device.sh
#
# A free-team signature expires after 7 days; re-run this to refresh. The app's
# data survives the re-install (same bundle id, same signing identity).
#
# DEBUG BY DEFAULT, and that is not a preference: the release entitlements
# (src-tauri/ios-entitlements/sable.release.entitlements) ask for aps-environment and
# an App Group, neither of which a free Personal Team can provision — the build fails
# at signing. The debug entitlements are empty, which is what a free team supports.
# Consequence: no APNs push on this build. Web push still works when the app is opened
# once against the web client's push gateway.
#
# Free-team caps (Apple): 3 devices, 3 apps per device, 10 App IDs per 7 days.
# Do NOT also sign this Apple ID into AltServer/AltStore while using Xcode installs —
# AltServer can mint or revoke the same development certificate and break the install.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO"

BUILD_ARGS=(--debug)
UDID_ARG=""
for arg in "$@"; do
  case "$arg" in
    --release) BUILD_ARGS=() ;;
    -*) : ;;
    *) UDID_ARG="$arg" ;;
  esac
done

export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"
export PATH="$HOME/.cargo/bin:$PATH"

# `tauri ios build` shells out to `xcodebuild`, and that child does not always inherit
# DEVELOPER_DIR — it then resolves through `xcode-select`, which on this host has pointed
# at CommandLineTools and failed with "tool 'xcodebuild' requires Xcode". A PATH shim
# makes the toolchain explicit regardless of what the CLI passes down.
SHIM="$HOME/.local/xcode-shim"
if [ ! -x "$SHIM/xcodebuild" ]; then
  mkdir -p "$SHIM"
  printf '%s\n' \
    '#!/bin/sh' \
    'export DEVELOPER_DIR="${DEVELOPER_DIR:-/Applications/Xcode.app/Contents/Developer}"' \
    'exec /usr/bin/xcodebuild "$@"' > "$SHIM/xcodebuild"
  chmod +x "$SHIM/xcodebuild"
fi
export PATH="$SHIM:$PATH"

if [ ! -d "src-tauri/gen/apple/maretrix.xcodeproj" ]; then
  echo "error: Xcode project missing — run: pnpm tauri ios init --ci" >&2
  exit 1
fi

if [ -z "${APPLE_DEVELOPMENT_TEAM:-}" ]; then
  # Fall back to the team embedded in the generated project, if any.
  APPLE_DEVELOPMENT_TEAM="$(grep -m1 'DEVELOPMENT_TEAM' src-tauri/gen/apple/maretrix.xcodeproj/project.pbxproj \
    | sed 's/.*DEVELOPMENT_TEAM = \(.*\);/\1/' | tr -d ' "')"
fi
if [ -z "${APPLE_DEVELOPMENT_TEAM:-}" ]; then
  echo "error: no development team. Sign into Xcode with an Apple ID (Settings → Accounts)," >&2
  echo "       then re-run, or pass APPLE_DEVELOPMENT_TEAM=<TEAMID>." >&2
  echo "       Team ids are listed by: security find-identity -v -p codesigning" >&2
  exit 1
fi
export APPLE_DEVELOPMENT_TEAM

UDID="${UDID_ARG:-}"
if [ -z "$UDID" ]; then
  UDID="$(xcrun devicectl list devices 2>/dev/null \
    | awk '/connected/ && $0 ~ /iPhone|iPad/ {print $3}' | head -1)"
fi
if [ -z "$UDID" ]; then
  echo "error: no connected iPhone/iPad found. Unlock the phone and trust this Mac." >&2
  xcrun devicectl list devices >&2 || true
  exit 1
fi
echo "device : $UDID"
echo "team   : $APPLE_DEVELOPMENT_TEAM"

# A Personal Team cannot provision `aps-environment` or App Groups, and `tauri ios init`
# writes both into the generated entitlements (app: aps-environment; share extension:
# the App Group). Signing fails with "provisioning profile doesn't include …" until they
# are stripped, so a free-team build blanks them. Cost: no APNs push, and the share
# extension cannot share a container with the app. Both are re-generated by `ios init`.
for f in \
  src-tauri/gen/apple/maretrix_iOS/maretrix_iOS.entitlements \
  src-tauri/gen/apple/share-extension/share-extension.entitlements; do
  [ -f "$f" ] || continue
  if grep -qE 'aps-environment|application-groups' "$f"; then
    printf '%s\n' \
      '<?xml version="1.0" encoding="UTF-8"?>' \
      '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">' \
      '<plist version="1.0">' \
      '<dict/>' \
      '</plist>' > "$f"
    echo "stripped free-team-incompatible entitlements: $f"
  fi
done

echo "building (Rust target aarch64-apple-ios + Xcode ${BUILD_ARGS[*]:-release})…"
pnpm tauri ios build "${BUILD_ARGS[@]}" 2>&1 | tail -25

IPA="$(find src-tauri/gen/apple/build -name '*.ipa' -newermt '-30 minutes' | head -1)"
if [ -z "$IPA" ]; then
  echo "error: no .ipa produced. Signed builds land in src-tauri/gen/apple/build/." >&2
  exit 1
fi
echo "ipa    : $IPA"

TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
unzip -q "$IPA" -d "$TMP"
APP="$(find "$TMP/Payload" -maxdepth 1 -name '*.app' | head -1)"
[ -n "$APP" ] || { echo "error: no .app inside $IPA" >&2; exit 1; }

echo "installing…"
xcrun devicectl device install app --device "$UDID" "$APP"

cat <<'EONOTE'

Installed. First launch on the phone will be refused until you trust the developer:
  Settings → General → VPN & Device Management → Apple Development: <your Apple ID> → Trust
The signature expires 7 days after it was issued; re-run this script to renew.
EONOTE
